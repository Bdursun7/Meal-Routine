-- V5 Smart Pantry. Canonical pantry schema. 0001-0011 are unchanged.
--
-- ingredients: the central dictionary. Seed rows (household_id NULL) come from this file.
-- Household rows are user-created `custom:<uuid>` ingredients registered through the API;
-- they are never merged with another ingredient by display name.
--
-- pantry_items: household pantry, server-authoritative. Personal pantry is device-only.
-- One row per household + ingredient + unit bucket: g/kg share `mass`, ml/l share `volume`,
-- every other unit is its own bucket. Compatible units merge into the existing row;
-- an incompatible unit needs an explicit "separate row" choice from the client.
--
-- pantry_idempotency: 24 hour replay cache. Removed with the account, and with the
-- household when the household is deleted, so no hidden pantry copy is left behind.

CREATE TABLE IF NOT EXISTS ingredients (
  id TEXT PRIMARY KEY CHECK (char_length(id) BETWEEN 1 AND 120),
  household_id UUID REFERENCES households (id) ON DELETE CASCADE,
  display_name TEXT NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 160),
  synonyms TEXT[] NOT NULL DEFAULT '{}',
  source_ids TEXT[] NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ingredients_scope CHECK (
    (household_id IS NULL AND id !~ '^custom:')
    OR (household_id IS NOT NULL AND id ~ '^custom:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
  )
);

CREATE INDEX IF NOT EXISTS ingredients_household_idx
  ON ingredients (household_id) WHERE household_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS pantry_items (
  id UUID PRIMARY KEY,
  household_id UUID NOT NULL REFERENCES households (id) ON DELETE CASCADE,
  ingredient_id TEXT NOT NULL REFERENCES ingredients (id),
  display_name TEXT NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 160),
  quantity NUMERIC(12,3) NOT NULL CHECK (quantity >= 0),
  unit TEXT NOT NULL CHECK (unit IN ('g', 'kg', 'ml', 'l', 'piece', 'tbsp', 'tsp', 'clove', 'pinch', 'slice', 'sprig', 'toTaste')),
  unit_bucket TEXT GENERATED ALWAYS AS (
    CASE WHEN unit IN ('g', 'kg') THEN 'mass' WHEN unit IN ('ml', 'l') THEN 'volume' ELSE unit END
  ) STORED,
  location TEXT NOT NULL CHECK (location IN ('pantry', 'refrigerator', 'freezer', 'other')),
  minimum_quantity NUMERIC(12,3) CHECK (minimum_quantity IS NULL OR minimum_quantity >= 0),
  date_type TEXT CHECK (date_type IN ('bestBefore', 'useBy')),
  date_value DATE,
  version INT NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pantry_items_date_pair CHECK ((date_type IS NULL) = (date_value IS NULL)),
  CONSTRAINT pantry_items_one_row_per_bucket UNIQUE (household_id, ingredient_id, unit_bucket)
);

CREATE INDEX IF NOT EXISTS pantry_items_household_idx
  ON pantry_items (household_id, updated_at);

CREATE TABLE IF NOT EXISTS pantry_idempotency (
  account_id UUID NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  idempotency_key TEXT NOT NULL,
  household_id UUID REFERENCES households (id) ON DELETE CASCADE,
  request_hash TEXT NOT NULL,
  response_body JSONB NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (account_id, idempotency_key)
);

CREATE INDEX IF NOT EXISTS pantry_idempotency_household_idx
  ON pantry_idempotency (household_id);

